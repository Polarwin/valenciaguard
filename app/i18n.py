"""Minimal i18n: plain-dict catalogs + contextvar-based per-request t().

Usage in templates:  {{ t("nav.dashboard") }}  /  {{ t("portal.greeting", name=owner.name) }}
Usage in routers:    t("users.err_username_taken", username=username)
Current language:    {{ lang }} in templates (e.g. <html lang="{{ lang }}">)

The request language is resolved from the `vg_lang` cookie (es/en/zh),
defaulting to Spanish. A pure-ASGI middleware in main.py sets the contextvar
once per request; contextvars propagate into sync endpoints and template
rendering, so t() always resolves the current request's language.
"""
from __future__ import annotations

import contextvars

SUPPORTED_LANGUAGES = ("es", "en", "zh")
DEFAULT_LANGUAGE = "es"
COOKIE_NAME = "vg_lang"

_current_lang: contextvars.ContextVar[str] = contextvars.ContextVar(
    "vg_current_lang", default=DEFAULT_LANGUAGE
)


def set_language(lang: str) -> None:
    _current_lang.set(lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE)


def current_language() -> str:
    return _current_lang.get()


def language_from_cookies(cookies: dict) -> str:
    lang = cookies.get(COOKIE_NAME, "")
    return lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translate(lang: str, key: str, **kwargs) -> str:
    """Look up key in lang's catalog; fall back es -> the key itself."""
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            pass
    return text


def t(key: str, **kwargs) -> str:
    """Translate using the current request's language (contextvar)."""
    return translate(_current_lang.get(), key, **kwargs)


class _LangProxy:
    """Jinja-visible object that renders as the current language code."""

    def __str__(self) -> str:
        return _current_lang.get()

    def __eq__(self, other) -> bool:
        return _current_lang.get() == other

    def __hash__(self) -> int:
        return hash(_current_lang.get())


